#Problem-1: Simple Math Input/Output

#Obtaining & Storing the Values
num_1 = int(input("Number-1 = "))
num_2 = int(input("Number-2 = "))

#Caculation/Operation & Storing Values
sum = num_1 + num_2
product = num_1 * num_2

#Printing the Results
print(f"Sum of {num_1} & {num_2} is {sum}")
print(f"Product of {num_1} & {num_2} is {product}")